    year INTEGER,
    attendance INTEGER,
    puzzles INTEGER,
    notes TEXT,
    recommendation TEXT,
    topics TEXT,
    rating INTEGER,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- 15. PUZZLE SCORES TABLE
-- Tracks puzzle solving history and XP for leaderboard.
CREATE TABLE IF NOT EXISTS public.puzzle_scores (
    id TEXT PRIMARY KEY,
    userId TEXT,
    userName TEXT,
    puzzleId TEXT,
    solved BOOLEAN,
    time INTEGER,
    mistakes INTEGER,
