-- 1. USERS TABLE
-- Stores students, coaches, admins, and parents.
CREATE TABLE IF NOT EXISTS public.users (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    userid TEXT,
    email TEXT,
    full_name TEXT,
    role TEXT,
    phone_number TEXT,
    city TEXT,
    level TEXT,
    rating INTEGER DEFAULT 800,
    coach TEXT,
    batch TEXT,
    session TEXT,
    schedule TEXT,
    fee TEXT,
    status TEXT,
    due_date TEXT,
    join_date TEXT,
    age INTEGER,
    grade TEXT,
    puzzle INTEGER DEFAULT 0,
    game INTEGER DEFAULT 0,
    star INTEGER DEFAULT 0,
    photo TEXT,
    certificate TEXT,
    last_note TEXT,
    childEmail TEXT, -- Used for parent accounts
    timetable TEXT, -- Used for coaches
    revenue TEXT,   -- Used for coaches
    classes INTEGER, -- Used for coaches
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- 2. EXPENSES TABLE
-- Tracks academy expenditures.
CREATE TABLE IF NOT EXISTS public.expenses (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    date TEXT,
    category TEXT,
    description TEXT,
    amount TEXT,
    mode TEXT,
    bill TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- 3. DOCUMENT TABLE
-- Stores uploaded documents and class files.
CREATE TABLE IF NOT EXISTS public.document (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    file_name TEXT,
    name TEXT,
    level TEXT,
    coach TEXT,
    batch TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- 4. ATTENDANCE TABLE
-- Tracks daily attendance for students.
CREATE TABLE IF NOT EXISTS public.attendance (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    userid TEXT,
    "studentId" TEXT,
    "studentName" TEXT,
    "classId" TEXT,
    "className" TEXT,
    "coachId" TEXT,
    "markedAt" TIMESTAMPTZ,
    date TEXT,
    status TEXT,
    class_title TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);
