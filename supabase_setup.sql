-- 17. ASSIGNMENTS TABLE
-- Stores homework tasks given by coaches to students.
CREATE TABLE IF NOT EXISTS public.assignments (
    id TEXT PRIMARY KEY,
    title TEXT,
    pgn TEXT,
    type TEXT, -- 'study', 'guess', 'practice'
