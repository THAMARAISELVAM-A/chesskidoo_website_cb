-- 16. COACH ATTENDANCE TABLE
-- Tracks when coaches join their own classes.
CREATE TABLE IF NOT EXISTS public.coach_attendance (
    id TEXT PRIMARY KEY,
    coachId TEXT,
    classId TEXT,
    date TEXT,
    joinedAt TIMESTAMP WITH TIME ZONE DEFAULT NOW()
